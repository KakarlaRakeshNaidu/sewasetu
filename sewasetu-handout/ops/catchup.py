"""Backed-up, manifested statutory catch-up on the operator's restored Compose database."""
import argparse,json,os,subprocess,tempfile
from datetime import datetime,timezone
from pathlib import Path
from backup import backup,dc,run,manifest


def query(sql):return json.loads(dc('exec','-T','db','psql','-U','sewasetu','-d','sewasetu','-Atc',sql,capture_output=True,text=True).stdout)


def catchup(destination,passphrase):
    snapshot=backup(destination,passphrase)
    running=dc('ps','--services','--status','running',capture_output=True,text=True).stdout.split()
    paused=[name for name in ['scheduler','app'] if name in running]
    info={'backup':str(snapshot)}
    stamp=datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')
    output=destination/('catchup-'+stamp+'.json.gpg')
    immutable="SELECT md5(string_agg(md5((to_jsonb(a)-'status'-'decided_at'-'decided_by')::text),'' ORDER BY id)) FROM applications a"
    try:
        if paused:dc('stop',*paused,stdout=subprocess.DEVNULL)
        before=query("SELECT json_build_object('at',clock_timestamp() AT TIME ZONE 'Asia/Kolkata','immutable',("+immutable+"),'eligible',COALESCE((SELECT json_agg(row_to_json(x)) FROM (SELECT id,status,submitted_at,decided_at,decided_by FROM applications WHERE status='PENDING' AND submitted_at<=(clock_timestamp() AT TIME ZONE 'Asia/Kolkata')-interval '15 days' ORDER BY id) x),'[]'::json))")
        info['before']=before;baseline=manifest()
        ids=','.join(str(int(row['id'])) for row in before['eligible'])
        predicate='id NOT IN ('+ids+')' if ids else 'TRUE'
        untouched="SELECT to_json(md5(string_agg(md5(json_build_array(id,status,decided_at,decided_by)::text),'' ORDER BY id))) FROM applications WHERE "+predicate
        original_untouched=query(untouched)
        dry=dc('run','--rm','--no-deps','app','python','/app/scripts/deemed_approval.py','--dry-run',capture_output=True,text=True)
        result=dc('run','--rm','--no-deps','app','python','/app/scripts/deemed_approval.py',capture_output=True,text=True)
        info['dry_run']=dry.stdout.strip();info['job']=result.stdout.strip()
        # Captured timestamps are generated by PostgreSQL, never supplied citizen input.
        at=before['at'];assert "'" not in at
        after=query("SELECT json_build_object('immutable',("+immutable+"),'changed',COALESCE((SELECT json_agg(row_to_json(x)) FROM (SELECT id,status,submitted_at,decided_at,decided_by FROM applications WHERE decided_by='RTPS-AUTO' AND decided_at>='"+at+"'::timestamp ORDER BY id) x),'[]'::json),'audit',(SELECT count(*) FROM application_audit WHERE event='DEEMED_APPROVED' AND occurred_at AT TIME ZONE 'Asia/Kolkata'>='"+at+"'::timestamp),'outbox',(SELECT count(*) FROM notification_outbox WHERE event_key LIKE 'DEEMED_APPROVED:%'))")
        info['after']=after;current=manifest()
        assert original_untouched==query(untouched),'A non-eligible decision changed'
        assert baseline['applications']==current['applications'] and after['outbox']>=len(after['changed'])
        assert before['immutable']==after['immutable'],'Unexpected non-decision application change'
        assert baseline['accounts']==current['accounts'] and baseline['account_digest']==current['account_digest'] and baseline['sequence']==current['sequence'],'Account or sequence changed'
        expected={row['id'] for row in before['eligible']};changed={row['id'] for row in after['changed']}
        assert expected==changed and after['audit']==len(changed),'Catch-up row/audit reconciliation failed'
        assert all(row['status']=='DEEMED_APPROVED' and row['decided_by']=='RTPS-AUTO' for row in after['changed'])
        info['reconciled']=True
    except BaseException as error:
        info['failure']=type(error).__name__
        raise
    finally:
        # Preserve the private evidence even if reconciliation fails; do not automatically undo decisions.
        try:
            with tempfile.TemporaryDirectory(prefix='sewasetu-catchup-') as temporary:
                file=Path(temporary)/'manifest.json';file.write_text(json.dumps(info,sort_keys=True));os.chmod(file,0o600)
                run(['gpg','--batch','--yes','--pinentry-mode','loopback','--passphrase-file',str(passphrase),'--symmetric','--cipher-algo','AES256','--output',str(output),str(file)],stdout=subprocess.DEVNULL,stderr=subprocess.PIPE)
                os.chmod(output,0o600)
        finally:
            if paused:dc('start',*paused,stdout=subprocess.DEVNULL)
    print(json.dumps({'eligible_changed':len(info['after']['changed']),'immutable_fields_accounts_sequence_preserved':True,'audit_rows':info['after']['audit'],'private_manifest':str(output),'notifications':'durably pending; delivery must be confirmed separately'}))


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--destination',required=True,type=Path)
    parser.add_argument('--passphrase-file',required=True,type=Path)
    args=parser.parse_args();catchup(args.destination.resolve(),args.passphrase_file.resolve())
